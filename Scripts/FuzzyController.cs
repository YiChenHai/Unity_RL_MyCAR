    // ===== 模糊推理接口 =====
    /// <summary>
    /// 基于聚类的模糊推理
    /// 每条规则的触发强度 = 各输入维度高斯隶属度的乘积
    /// 输出 = 加权平均 (Takagi-Sugeno零阶去模糊化)
    /// </summary>
    public static void Evaluate(
        float frontLRDiff, float rearLRDiff,
        float frontCenter, float rearCenter,
        out float outputVx, out float outputOmega)
    {
        float sumWVx = 0f, sumWOmega = 0f, sumW = 0f;

        for (int r = 0; r < N_RULES; r++)
        {
            // 各输入维度的高斯隶属度乘积 (AND运算)
            float firing = GaussMF(frontLRDiff, Centers[r, 0], Sigmas[r, 0])
                         * GaussMF(rearLRDiff,  Centers[r, 1], Sigmas[r, 1])
                         * GaussMF(frontCenter, Centers[r, 2], Sigmas[r, 2])
                         * GaussMF(rearCenter,  Centers[r, 3], Sigmas[r, 3]);

            if (firing > 1e-6f)
            {
                sumWVx    += firing * Outputs[r, 0];
                sumWOmega += firing * Outputs[r, 1];
                sumW      += firing;
            }
        }

        // Takagi-Sugeno零阶去模糊化: 加权平均
        if (sumW > 1e-6f)
        {
            outputVx    = Mathf.Clamp(sumWVx / sumW, -1f, 1f);
            outputOmega = Mathf.Clamp(sumWOmega / sumW, -1f, 1f);
        }
        else
        {
            outputVx = 0f;
            outputOmega = 0f;
        }
    }

    // ===== 高斯隶属函数 =====
    // μ(x) = exp(-(x-c)²/(2σ²))
    private static float GaussMF(float x, float center, float sigma)
    {
        float d = x - center;
        return Mathf.Exp(-d * d / (2f * sigma * sigma));
    }

    // ===== 便捷方法 =====
    /// <summary>
    /// 直接从6个传感器原始值计算控制输出
    /// </summary>
    public static void EvaluateFromSensors(
        float sensorFL, float sensorFC, float sensorFR,
        float sensorRL, float sensorRC, float sensorRR,
        float maxField,
        out float outputVx, out float outputOmega)
    {
        float invMax = 1f / Mathf.Max(1e-6f, maxField);
        float frontLRDiff = Mathf.Clamp((sensorFL - sensorFR) * invMax, -1f, 1f);
        float rearLRDiff = Mathf.Clamp((sensorRL - sensorRR) * invMax, -1f, 1f);
        float frontCenter = Mathf.Clamp01(sensorFC * invMax);
        float rearCenter = Mathf.Clamp01(sensorRC * invMax);
        Evaluate(frontLRDiff, rearLRDiff, frontCenter, rearCenter, out outputVx, out outputOmega);
    }

